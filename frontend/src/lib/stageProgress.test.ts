import { describe, it, expect } from "vitest";
import type { Stage } from "@/types";
import {
  GENERATE_STAGE,
  REVIEW_STAGE,
  optimisticSteps,
  reconcileSteps,
  trustLine,
} from "./stageProgress";

function generateStage(overrides: Partial<Stage> = {}): Stage {
  return {
    stage: GENERATE_STAGE,
    model_id: "us.anthropic.claude-sonnet-4-5-20250929-v1:0",
    model_label: "Claude Sonnet 4.5",
    status: "complete",
    fallback: null,
    ...overrides,
  };
}

function reviewStage(overrides: Partial<Stage> = {}): Stage {
  return {
    stage: REVIEW_STAGE,
    model_id: "us.amazon.nova-lite-v1:0",
    model_label: "Nova Lite",
    status: "complete",
    fallback: false,
    ...overrides,
  };
}

describe("trustLine", () => {
  it("generate + review -> full trust line", () => {
    const line = trustLine([generateStage(), reviewStage()]);
    expect(line).toBe("Generated by Claude Sonnet 4.5, reviewed by Nova Lite");
  });

  it("generate only -> no trust line", () => {
    expect(trustLine([generateStage()])).toBeNull();
  });

  it("no stages -> no trust line", () => {
    expect(trustLine(undefined)).toBeNull();
  });

  it("review stage status error -> degraded line", () => {
    const line = trustLine([generateStage(), reviewStage({ status: "error" })]);
    expect(line).toBe("Generated by Claude Sonnet 4.5; review unavailable");
  });

  it("surfaces the fallback review model via its own label", () => {
    const line = trustLine([
      generateStage(),
      reviewStage({ model_label: "Nova Micro", fallback: true }),
    ]);
    expect(line).toBe("Generated by Claude Sonnet 4.5, reviewed by Nova Micro");
  });
});

describe("optimistic steps + reconciliation", () => {
  it("builds a generate + review optimistic sequence", () => {
    const steps = optimisticSteps("Claude Sonnet 4.5", "Nova Lite");
    expect(steps.map((s) => s.stage)).toEqual([GENERATE_STAGE, REVIEW_STAGE]);
    expect(steps[0].label).toBe("Generating with Claude Sonnet 4.5");
    expect(steps[1].label).toBe("Reviewing with Nova Lite");
  });

  it("keeps the review step when the response has a review stage", () => {
    const steps = optimisticSteps("Sonnet", "Nova Lite");
    const reconciled = reconcileSteps(steps, [generateStage(), reviewStage()]);
    expect(reconciled.map((s) => s.stage)).toEqual([GENERATE_STAGE, REVIEW_STAGE]);
  });

  it("drops the optimistic review step when the response ran no review", () => {
    const steps = optimisticSteps("Sonnet", "Nova Lite");
    const reconciled = reconcileSteps(steps, [generateStage()]);
    expect(reconciled.map((s) => s.stage)).toEqual([GENERATE_STAGE]);
  });

  it("drops the review step when there are no stages at all", () => {
    const steps = optimisticSteps("Sonnet", "Nova Lite");
    const reconciled = reconcileSteps(steps, undefined);
    expect(reconciled.map((s) => s.stage)).toEqual([GENERATE_STAGE]);
  });
});
