/**
 * Pure helpers for the chat stage indicator and the who-did-what trust line.
 *
 * These are deterministic functions over a `stages` array (the authoritative
 * generate -> review pipeline the Runtime projects back, FEAT-001/FEAT-002) so
 * they can be unit-tested without React. The chat page drives an optimistic
 * two-step indicator while the request is in flight, then reconciles it against
 * the real stages when the response arrives.
 */

import type { Stage } from "@/types";

export const GENERATE_STAGE = "generate";
export const REVIEW_STAGE = "review";

/** An optimistic (client-predicted) step shown while the turn is in flight. */
export interface OptimisticStep {
  stage: string;
  label: string;
}

/** Find a stage by its `stage` name, or undefined. */
export function findStage(stages: Stage[] | undefined, name: string): Stage | undefined {
  return stages?.find((s) => s.stage === name);
}

/**
 * The optimistic steps shown before the response arrives: always a generate
 * step, plus a review step (we assume a code turn will be reviewed). On
 * reconciliation the review step is dropped if the response ran no review.
 */
export function optimisticSteps(
  genLabel: string,
  reviewLabel: string,
): OptimisticStep[] {
  return [
    { stage: GENERATE_STAGE, label: `Generating with ${genLabel}` },
    { stage: REVIEW_STAGE, label: `Reviewing with ${reviewLabel}` },
  ];
}

/**
 * Reconcile optimistic steps against the authoritative response stages: drop the
 * optimistic review step when the response carries no review stage (a no-code
 * turn that never reached review).
 */
export function reconcileSteps(
  optimistic: OptimisticStep[],
  stages: Stage[] | undefined,
): OptimisticStep[] {
  const hasReview = Boolean(findStage(stages, REVIEW_STAGE));
  if (hasReview) {
    return optimistic;
  }
  return optimistic.filter((step) => step.stage !== REVIEW_STAGE);
}

/**
 * Derive the who-did-what trust line from the authoritative stages:
 *  - no review stage -> null (a no-code turn shows no trust line);
 *  - review stage in error -> "Generated by X; review unavailable";
 *  - otherwise -> "Generated by X, reviewed by Y".
 * The labels come from the stage's own `model_label` (which already reflects a
 * fallback review model when the server fell back).
 */
export function trustLine(stages: Stage[] | undefined): string | null {
  const review = findStage(stages, REVIEW_STAGE);
  if (!review) {
    return null;
  }

  const generate = findStage(stages, GENERATE_STAGE);
  const genLabel = generate?.model_label ?? "the code model";

  if (review.status === "error") {
    return `Generated by ${genLabel}; review unavailable`;
  }

  return `Generated by ${genLabel}, reviewed by ${review.model_label}`;
}
